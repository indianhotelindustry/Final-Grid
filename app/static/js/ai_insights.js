/**
 * AI Insights — Module 7 (Gemini)
 * --------------------------------
 * Loads /api/ai/insights asynchronously after the dashboard has rendered,
 * so the LLM call never blocks the page. Renders summary + issues + actions
 * into the panel defined in tabs/test_view.html.
 *
 * Falls back gracefully if the panel isn't on the page (FrontDesk users
 * don't get the Intelligence Panel at all) — the early return below makes
 * this script a no-op for those roles.
 */
(function () {
    'use strict';

    const panel = document.getElementById('aiInsightsPanel');
    if (!panel) return;

    const endpoint = panel.dataset.endpoint;
    const refreshEndpoint = panel.dataset.refreshEndpoint;

    const elSummary  = document.getElementById('aiInsightsSummary');
    const elIssues   = document.getElementById('aiInsightsIssues');
    const elActions  = document.getElementById('aiInsightsActions');
    const elSource   = document.getElementById('aiInsightsSource');
    const elTime     = document.getElementById('aiInsightsTime');
    const btnRefresh = document.getElementById('aiInsightsRefresh');

    function escapeHTML(s) {
        return String(s == null ? '' : s)
            .replace(/&/g, '&amp;')
            .replace(/</g, '&lt;')
            .replace(/>/g, '&gt;')
            .replace(/"/g, '&quot;')
            .replace(/'/g, '&#39;');
    }

    function fmtTime(iso) {
        if (!iso) return '';
        try {
            const d = new Date(iso);
            if (isNaN(d.getTime())) return '';
            return d.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
        } catch (_) { return ''; }
    }

    function render(insights) {
        // Summary
        elSummary.textContent = insights.summary || '(no summary)';

        // Source badge
        const src = insights.source || 'unknown';
        elSource.textContent = src === 'gemini'
            ? 'Gemini'
            : (src === 'heuristic' ? 'Offline rules' : src);
        elSource.className = 'ai-source-badge' + (src === 'heuristic' ? ' heuristic' : '');
        elSource.title = insights.model
            ? `Generated by ${insights.model}`
            : 'Generated locally without an LLM';

        // Generated-at time
        elTime.textContent = insights.generated_at
            ? `at ${fmtTime(insights.generated_at)}`
            : '';

        // Issues
        const issues = insights.issues || [];
        if (issues.length === 0) {
            elIssues.innerHTML =
                '<div class="ai-insights-empty">No issues detected — the day looks healthy.</div>';
        } else {
            elIssues.innerHTML = issues.map(function (it) {
                const title  = escapeHTML(it.title || '');
                const reason = escapeHTML(it.reason || '');
                return (
                    '<div class="ai-insights-item">' +
                      '<i class="bi bi-dot bullet"></i>' +
                      '<div>' +
                        '<div class="issue-title">' + title + '</div>' +
                        (reason ? '<div class="issue-reason">' + reason + '</div>' : '') +
                      '</div>' +
                    '</div>'
                );
            }).join('');
        }

        // Actions
        const actions = insights.actions || [];
        if (actions.length === 0) {
            elActions.innerHTML =
                '<div class="ai-insights-empty">No specific actions needed right now.</div>';
        } else {
            elActions.innerHTML = actions.map(function (a) {
                return (
                    '<div class="ai-insights-item">' +
                      '<i class="bi bi-arrow-right-circle bullet"></i>' +
                      '<div>' + escapeHTML(a) + '</div>' +
                    '</div>'
                );
            }).join('');
        }
    }

    function showError(msg) {
        elSource.textContent = 'error';
        elSource.className = 'ai-source-badge heuristic';
        elSummary.innerHTML = '<span class="ai-insights-error">' + escapeHTML(msg) + '</span>';
        elIssues.innerHTML = '';
        elActions.innerHTML = '';
    }

    function load(url, method) {
        method = method || 'GET';
        btnRefresh.disabled = true;
        const opts = { method: method, headers: { 'Accept': 'application/json' } };
        if (method === 'POST') {
            // Send the CSRF token if the page exposes one (Flask-WTF style).
            const csrfMeta = document.querySelector('meta[name="csrf-token"]');
            if (csrfMeta) {
                opts.headers['X-CSRFToken'] = csrfMeta.getAttribute('content');
            }
        }
        return fetch(url, opts)
            .then(function (r) {
                if (!r.ok) throw new Error('HTTP ' + r.status);
                return r.json();
            })
            .then(function (data) {
                if (data.status !== 'ok' || !data.insights) {
                    throw new Error(data.error || 'Bad response');
                }
                render(data.insights);
            })
            .catch(function (err) {
                console.error('AI insights load failed:', err);
                showError('Could not load insights — ' + (err.message || 'unknown error'));
            })
            .then(function () {
                btnRefresh.disabled = false;
            });
    }

    btnRefresh.addEventListener('click', function () {
        elSummary.innerHTML = '<span class="text-muted">Regenerating insights…</span>';
        elIssues.innerHTML = '<div class="ai-insights-empty">Loading…</div>';
        elActions.innerHTML = '<div class="ai-insights-empty">Loading…</div>';
        load(refreshEndpoint, 'POST');
    });

    // Initial load — kick off after the rest of the dashboard has settled
    // so we never delay above-the-fold rendering.
    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', function () { load(endpoint); });
    } else {
        load(endpoint);
    }
})();
